const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
const base=process.env.COUNTRY_URL||'http://localhost:4187';
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
 const errors=[],checks=[];
 try{
  const tablet=await browser.newPage({viewport:{width:1024,height:768},hasTouch:true});
  const tv=await browser.newPage({viewport:{width:1920,height:1080}});
  for(const page of [tablet,tv])page.on('pageerror',e=>errors.push(e.message));
  await tablet.goto(base+'/projects/10-vpc-country-intelligence/index.html?station=10');
  await tablet.locator('[data-start]').tap();
  await tablet.frameLocator('iframe').locator('[data-ci-back]').waitFor();
  assert.equal(await tablet.frameLocator('iframe').locator('[data-lang]').count(),0);
  await tablet.frameLocator('iframe').locator('[data-ci-back]').click();
  await tv.goto(base+'/display.html?station=10');
  await tv.locator('.ci-cover').waitFor();
  assert.equal(await tv.locator('.ci-cover button').count(),0);
  for(const [width,height] of [[1024,768],[1180,820],[1920,1080]]){
   await tablet.setViewportSize({width,height});
   assert(await tablet.evaluate(()=>document.documentElement.scrollWidth<=innerWidth&&document.documentElement.scrollHeight<=innerHeight));
   await tablet.screenshot({path:path.join(__dirname,`cover-${width}.png`)});
  }
  checks.push('Responsive cover at 1024, 1180 and 1920; display options are read-only');
  await tablet.setViewportSize({width:1024,height:768});
  const coverBefore=await tablet.locator('.ci-cover').innerText();
  const cardBefore=await tablet.locator('[data-info]').boundingBox();
  await tablet.locator('[data-info]').tap();
  await tv.locator('.ci-infographic').waitFor();
  assert.equal(await tablet.locator('.ci-cover').innerText(),coverBefore);
  assert.deepEqual(await tablet.locator('[data-info]').boundingBox(),cardBefore);
  assert.equal(await tablet.locator('[data-info]').getAttribute('aria-pressed'),'true');
  assert.equal(await tablet.locator('.ci-infographic').count(),0);
  assert.equal(await tablet.locator('button').count(),3);
  assert.equal(await tablet.locator('.ci-shell [data-home]').count(),1);
  assert.equal(await tablet.locator('.ci-languages,.ci-navigation,[data-fullscreen]').count(),0);
  await tablet.screenshot({path:path.join(__dirname,'tablet-infographic-selected.png')});
  await tablet.reload();await tablet.locator('[data-info][aria-pressed="true"]').waitFor();
  checks.push('Tablet has only Home and two cards; infographic selection only changes the perimeter and survives reload');
  const delays=await tv.evaluate(()=>['.ci-info-challenge','.ci-info-solution','.ci-metric-0','.ci-metric-3'].map(s=>parseFloat(getComputedStyle(document.querySelector(s)).animationDelay)));
  assert(delays.every((d,i)=>i===0||d>delays[i-1]));
  await tv.screenshot({path:path.join(__dirname,'animation-start.png')});
  await tablet.waitForTimeout(7300);
  assert.equal(await tv.locator('.ci-metric-3').evaluate(e=>getComputedStyle(e).opacity),'1');
  for(const page of [tablet,tv])assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth&&document.documentElement.scrollHeight<=innerHeight));
  await tv.screenshot({path:path.join(__dirname,'infographic-final-en.png')});
  const before=await tablet.request.get(base+'/api/state?station=10').then(r=>r.json());
  await tablet.locator('[data-info]').tap();
  await tv.waitForFunction(()=>parseFloat(getComputedStyle(document.querySelector('.ci-metric-3')).opacity)<1);
  const after=await tablet.request.get(base+'/api/state?station=10').then(r=>r.json());
  assert(after.game.lastActive>before.game.lastActive);
  await tv.reload();await tv.locator('.ci-infographic').waitFor();
  checks.push('Staged animation, final values, tablet replay and TV reload');
  await tv.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await tv.locator('.ci-blue-wipe').evaluate(e=>getComputedStyle(e).display),'none');
  assert.equal(await tv.locator('.ci-metric-3').evaluate(e=>getComputedStyle(e).opacity),'1');
  await tablet.locator('[data-start]').tap();
  await tablet.frameLocator('iframe').locator('[data-ci-back]').waitFor();
  await tablet.frameLocator('iframe').locator('[data-ci-back]').tap();
  await tablet.locator('[data-info]').tap();
  await tv.getByText('Fragmented Country Insights',{exact:true}).waitFor();
  assert.equal(await tv.locator('.ci-infographic').innerText().then(s=>s.includes('?')),false);
  checks.push('Reduced motion shows all information immediately; experience and infographic remain English-only');
  await tablet.locator('[data-start]').tap();
  await tablet.frameLocator('iframe').locator('[data-go="problem"]').waitFor();
  await tablet.frameLocator('iframe').locator('[data-ci-back]').tap();
  await tablet.locator('[data-info]').waitFor();
  assert.equal(await tablet.locator('[data-info]').getAttribute('aria-pressed'),'false');
  await tablet.locator('[data-home]').tap();
  await tablet.waitForURL('**/index.html?station=10&projects=1');
  await tablet.locator('[data-project="10"]').waitFor();
  checks.push('Back from the game clears selection; the single Home button opens the exhibition menu');
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(__dirname,'presentation-report.json'),JSON.stringify({checks,errors},null,2));
  console.log(JSON.stringify({checks,errors},null,2));
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
